import type { GeoQuestionPlan, QuestionCategory } from './question-types';
import type { AnswerAuditRecord, OverviewMetricScopes } from './overview-metrics';

export type ResearchEngine =
  | 'chatgpt'
  | 'google'
  | 'deepseek'
  | 'qwen'
  | 'doubao';

export interface ResearchSource {
  title: string;
  url: string;
  kind: 'official' | 'other' | 'self_submission' | 'mirror';
  position?: number;
}

export interface ResearchObservation {
  id?: string;
  runId?: string;
  collectedAt?: string;
  entryType?: 'web_answer' | 'web_search' | 'api_answer' | 'api_search';
  engine: ResearchEngine;
  language: 'zh' | 'en';
  query: string;
  recordedAt: string;
  status: 'found' | 'not_observed';
  summary: string;
  conditions: string;
  sources: ResearchSource[];
  evidencePath: string;
  answerPath?: string;
  overviewStatus?: string;
}

export interface ResearchQuestion {
  id: string;
  candidateId?: string;
  questionPlanRevision?: number;
  category?: QuestionCategory;
  zh: string;
  en: string;
  decision: 'search_now' | 'keep_and_fill' | 'drop_for_now';
  valueReason: string;
  evidenceBasis: string;
  answerability: string;
  gaps: string[];
  decisionReason: string;
  reviewPath: string;
  observations: ResearchObservation[];
  diagnosis: { observed: string; hypothesis: string; nextStep: string };
}

export interface ResearchBatch {
  id: string;
  /** Server-loaded per-answer reviews; never generated by a page read. */
  answerAudits?: AnswerAuditRecord[];
  /** Backend summaries keyed by language:engine (including language:all). */
  overviewMetrics?: OverviewMetricScopes;
  /** Immutable source snapshot for batches created by explicit confirmation. */
  questionPlan?: GeoQuestionPlan;
  updatedAt?: string;
  date: string;
  projectId: string;
  productSummary: string;
  contributionSummary: string;
  scopeNote: string;
  reportPath: string;
  sourceAuditPath: string;
  reviewPath: string;
  questions: ResearchQuestion[];
  deferredQuestions: ResearchQuestion[];
  nextStep: string;
}
