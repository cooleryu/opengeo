import type { ResearchBatch, ResearchEngine } from './research-types';

export type GeoLanguage = 'en' | 'zh';

/**
 * Determine the target market language (`en` | `zh`) used for search queries,
 * answer evidence drawers, and deliverable drafts.
 * Defaults to `'en'` for new projects while respecting explicit project settings
 * and observed recordings in existing batches.
 */
export function resolveProjectTargetLanguage(
  project?: { targetLanguage?: GeoLanguage } | null,
  batch?: Pick<ResearchBatch, 'questions'> | null,
): GeoLanguage {
  const hasEn = Boolean(
    batch?.questions.some((q) => q.observations.some((obs) => obs.language === 'en')),
  );
  const hasZh = Boolean(
    batch?.questions.some((q) => q.observations.some((obs) => obs.language === 'zh')),
  );

  if (project?.targetLanguage === 'en') {
    return hasEn || !hasZh ? 'en' : 'zh';
  }
  if (project?.targetLanguage === 'zh') {
    return hasZh || !hasEn ? 'zh' : 'en';
  }
  if (hasEn) return 'en';
  if (hasZh) return 'zh';
  return 'en';
}

/**
 * Resolve the project's locked display & report language (`en` | `zh`).
 * Uses explicit saved `uiLanguage` when available, otherwise infers from
 * existing project summary/description so legacy Chinese projects stay Chinese.
 */
export function resolveProjectUiLanguage(
  input?: { uiLanguage?: GeoLanguage; summaryOrDescription?: string } | null,
): GeoLanguage {
  if (input?.uiLanguage === 'en' || input?.uiLanguage === 'zh') {
    return input.uiLanguage;
  }
  if (input?.summaryOrDescription && /[\p{Script=Han}]/u.test(input.summaryOrDescription)) {
    return 'zh';
  }
  return 'en';
}

