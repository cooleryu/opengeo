export const UI_MESSAGES: Record<GeoLanguage, Record<UiMessageKey, string>> = {
  zh: zhMessages,
  en: enMessages,
};

export function translateUi(
  lang: GeoLanguage,
  key: UiMessageKey,
  vars?: Record<string, string | number>,
): string {
  const table = UI_MESSAGES[lang] ?? UI_MESSAGES.en;
  let text = table[key] ?? UI_MESSAGES.en[key];
  if (vars) {
    for (const [varKey, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${varKey}}`, String(value));
    }
  }
  return text;
}

